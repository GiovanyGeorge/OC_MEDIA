/**
 * Firestore Document Type Definitions — OC Media Platform
 * Phase 1: TypeScript interfaces for all Firestore collections.
 *
 * These types mirror the approved Firestore schema exactly.
 * They are used only for type-safe Firestore operations in the frontend.
 * They do NOT define or enforce security rules (that is firestore.rules).
 */

import type { Timestamp } from 'firebase/firestore';

// ---------------------------------------------------------------------------
// Shared primitives
// ---------------------------------------------------------------------------

/** All possible applicant / member account lifecycle states */
export type ApplicationStatus = 'pending' | 'approved' | 'rejected';

/** Activation state machine stages */
export type ActivationStatus =
  | 'approved'               // Admin approved application, eligible for activation
  | 'code_issued'            // Admin generated one-time activation code
  | 'activation_in_progress' // Activation request currently processing with lock
  | 'active'                 // Successfully activated, member profile created
  | 'activation_failed'      // Activation attempt failed, safe to retry
  | 'recovery_required'      // Rollback double-fault (orphaned Auth user), requires reconciliation
  | 'suspended';             // Member account has been administratively suspended

/** Member roles — only two exist */
export type MemberRole = 'admin' | 'member';

/** Portfolio item media type */
export type PortfolioItemType = 'link' | 'image' | 'drive_pdf';

// ---------------------------------------------------------------------------
// Collection: applications/{referenceId}
// ---------------------------------------------------------------------------

/**
 * Recruitment application submitted via Google Forms → Apps Script → Firestore.
 * Document ID = referenceId (e.g. "OC-2026-0001").
 * Access: Admin read/write only.
 */
export interface ApplicationDocument {
  referenceId: string;
  fullName: string;
  phone: string;
  academicYear: string;
  skills: string[];
  equipment: string[];
  hasPortfolio: boolean;
  portfolioUrl?: string;

  /** Current review status */
  status: ApplicationStatus;

  /** Whether the applicant has completed account activation */
  isActivated: boolean;

  /** Activation state machine */
  activationStatus?: ActivationStatus;

  /** SHA-256 keyed HMAC of the one-time activation code (never the plaintext) */
  activationCodeHash?: string;

  /** When the activation code expires */
  activationCodeExpiresAt?: Timestamp;

  /** Concurrency control lock token for in-flight activation */
  lockToken?: string;

  /** Lock expiration timestamp to prevent deadlock */
  lockExpiresAt?: Timestamp;

  /** Current or last operation ID */
  operationId?: string;

  /** Orphan Auth UID if rollback failed during account creation */
  orphanAuthUid?: string;

  /** Flag indicating an administrator must reconcile this orphaned account */
  recoveryRequired?: boolean;

  /** Detail reason for recovery requirement */
  recoveryReason?: string;

  /** Firebase Auth UID assigned after successful activation */
  memberUid?: string;

  /** Admin notes (internal, never shown to member) */
  adminNotes?: string;

  createdAt: Timestamp;
  updatedAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Collection: members/{uid}
// ---------------------------------------------------------------------------

/**
 * Member profile document, created by the activation backend.
 * Document ID = Firebase Auth UID.
 * Access: Owner (read + limited update) | Admin (full read/write).
 *
 * Fields the MEMBER may update: currentSkills, currentEquipment, phone, bio, updatedAt.
 * All other fields are admin-only or immutable.
 */
export interface MemberDocument {
  uid: string;
  referenceId: string;
  fullName: string;
  email: string;           // Synthetic: {refId.toLowerCase()}@ocmedia.internal
  phone: string;
  role: MemberRole;
  accountStatus: 'active' | 'suspended';

  academicYear: string;
  currentSkills: string[];
  currentEquipment: string[];
  bio?: string;

  createdAt: Timestamp;
  updatedAt: Timestamp;
  activatedAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Collection: activationCodes/{codeHash}
// ---------------------------------------------------------------------------

/**
 * One-time activation codes generated by Admin.
 * Document ID = SHA-256 hash of the plaintext code.
 * Access: Backend Admin SDK ONLY — `allow read, write: if false` in rules.
 *
 * Plaintext code is shown to the Admin ONCE and never stored.
 */
export interface ActivationCodeDocument {
  referenceId: string;
  codeHash: string;          // SHA-256(plaintext code) — the document ID
  expiresAt: Timestamp;      // 7 days after generation
  used: boolean;
  usedAt?: Timestamp;
  failedAttempts: number;    // Rate-limiting counter
  lockedUntil?: Timestamp;   // Temporary lockout after repeated failures
  createdAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Collection: adminUsers/{uid}
// ---------------------------------------------------------------------------

/**
 * Trusted admin registry. Populated ONLY by the backend (service account).
 * Document ID = Firebase Auth UID.
 * Access: Admin read/write only — members must NEVER read this collection.
 */
export interface AdminUserDocument {
  uid: string;
  email: string;
  displayName: string;
  grantedAt: Timestamp;
  grantedBy: string;         // UID of the admin who granted this role
}

// ---------------------------------------------------------------------------
// Collection: portfolios/{itemId}
// ---------------------------------------------------------------------------

/**
 * Portfolio items uploaded/linked by members.
 * Document ID = auto-generated Firestore ID.
 * Access: Owner (read/write) | Admin (read/write).
 *
 * memberUid is immutable after creation — cannot be changed even by owner.
 */
export interface PortfolioDocument {
  itemId: string;
  memberUid: string;         // Immutable — must equal auth.uid at creation
  title: string;             // max 200 chars
  description?: string;      // max 500 chars
  url: string;               // Must be a valid URL, max 500 chars
  type: PortfolioItemType;
  driveFileId?: string;      // Google Drive file ID (never a public URL)
  tags?: string[];
  isPublic: boolean;
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Collection: evaluations/{targetUid}
// ---------------------------------------------------------------------------

/**
 * Admin evaluation of a member's performance.
 * Document ID = member UID being evaluated.
 * Access: Owner (read) | Admin (read/write).
 */
export interface EvaluationDocument {
  targetUid: string;
  evaluatedBy: string;       // Admin UID
  overallRating: number;     // 1–5
  categoryRatings: Record<string, number>;
  strengths?: string;
  areasForImprovement?: string;
  evaluatedAt: Timestamp;
  updatedAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Collection: feedback/{fbId}
// ---------------------------------------------------------------------------

/**
 * Feedback given to a member by admin.
 * Document ID = auto-generated Firestore ID.
 * Access: Owner (resource.data.memberUid == auth.uid, read) | Admin (read/write).
 */
export interface FeedbackDocument {
  fbId: string;
  memberUid: string;
  authorUid: string;         // Admin UID
  message: string;
  isRead: boolean;
  createdAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Collection: privateNotes/{noteId}
// ---------------------------------------------------------------------------

/**
 * Internal admin-only notes about members or applications.
 * Document ID = auto-generated Firestore ID.
 * Access: Admin ONLY — completely inaccessible to members.
 */
export interface PrivateNoteDocument {
  noteId: string;
  targetType: 'member' | 'application';
  targetId: string;          // memberUid or referenceId
  authorUid: string;
  content: string;
  createdAt: Timestamp;
  updatedAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Collection: systemSettings/{settingDoc}
// ---------------------------------------------------------------------------

/**
 * Platform-wide configuration.
 * Document 'public' is readable by everyone (unauthenticated).
 * All other documents are admin-only.
 */
export interface SystemSettingsPublicDocument {
  platformName: string;
  recruitmentOpen: boolean;
  currentCohort: string;
  whatsappGroupLink?: string;
  updatedAt: Timestamp;
}

export interface SystemSettingsPrivateDocument {
  activationCodeTtlDays: number;
  maxFailedActivationAttempts: number;
  lockoutDurationMinutes: number;
  adminEmails: string[];
  updatedAt: Timestamp;
}
